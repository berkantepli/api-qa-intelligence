from datetime import UTC, datetime

from app.domain.html_report import (
    HtmlReportRequest,
    ReportCheck,
    ReportCoverage,
    ReportCoverageEndpoint,
    render_html_report,
)
from app.domain.run_compare import CheckRecord, compare_runs

FIXED = datetime(2026, 10, 14, 12, 0, tzinfo=UTC)


def check(result, **values):
    return ReportCheck(**{"group": "GET /books", "title": f"{result} check", "result": result, "duration_ms": 12, **values})


def render(**values):
    return render_html_report(HtmlReportRequest(title="GET /books", api="Demo Bookstore", **values), "1.20.0", FIXED)


def test_is_one_file_that_loads_and_runs_nothing():
    html = render(checks=[check("PASS")])

    assert html.startswith("<!doctype html>")
    assert "default-src 'none'" in html
    assert "<script" not in html and "<link" not in html and "src=" not in html
    assert "Generated by API QA Intelligence 1.20.0 on 14 Oct 2026, 12:00 UTC." in html


def test_escapes_whatever_the_api_returned():
    html = render(checks=[check("FAIL", response_status=200, response_body='<script>alert("x")</script>', title='<img src=x onerror=1>')])

    assert "<script>alert" not in html
    assert "&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;" in html
    assert "<img src=x" not in html


def test_shows_evidence_for_failures_and_passes_only_on_request():
    checks = [
        check("FAIL", response_status=500, response_body="boom", message="Expected HTTP 200, received HTTP 500.", schema_errors=["$.price: expected number"]),
        check("PASS", response_status=200, response_body="all good"),
    ]

    html = render(checks=checks)
    assert "boom" in html and "$.price: expected number" in html and "Expected HTTP 200, received HTTP 500." in html
    assert "all good" not in html
    assert "Evidence is included for failed checks and errors only." in html
    assert "all good" in render(checks=checks, include_passing_evidence=True)


def test_summary_counts_and_failures_first():
    html = render(checks=[check("PASS"), check("FAIL"), check("ERROR"), check("SKIPPED")])

    assert '<span>Checks</span><strong>4</strong>' in html
    assert '<span>Skipped</span><strong>1</strong>' in html
    assert html.index("FAIL check") < html.index("PASS check")


def test_long_bodies_are_cut():
    html = render(checks=[check("FAIL", response_status=500, response_body="x" * 20_000)])

    assert "cut at 10,000 characters" in html


def test_comparison_and_coverage_sections():
    comparison = compare_runs(
        [CheckRecord(endpoint="GET /books", title="Valid request", result="PASS")],
        [CheckRecord(endpoint="GET /books", title="Valid request", result="FAIL", message="price is text")],
    )
    coverage = ReportCoverage(
        tested=1, endpoints=2, failing=1, coverage_percent=50, quality_score=92, quality_grade="A", flows_passing=1, flows_total=1,
        items=[
            ReportCoverageEndpoint(key="GET /books", status="failing", covered=1, runnable=2, risks=["Only happy path tested"]),
            ReportCoverageEndpoint(key="GET /me", status="untested"),
        ],
    )

    html = render(comparison=comparison, comparison_label="the previous run", coverage=coverage)

    assert "Changes since the previous run" in html
    assert "Newly failing" in html and "PASS → FAIL · price is text" in html
    assert "92 / 100 (A)" in html and "Not tested" in html and "Only happy path tested" in html
    assert html.index("GET /books") < html.index("GET /me")


def test_html_route(client):
    response = client.post("/api/v1/reports/html", json={"title": "Coverage", "api": "Pets", "checks": [{"group": "GET /a", "title": "x", "result": "PASS"}]})

    assert response.status_code == 200
    assert response.headers["content-type"].startswith("text/html")
    assert "<h1>Coverage</h1>" in response.text
